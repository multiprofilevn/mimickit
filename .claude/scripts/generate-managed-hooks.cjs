#!/usr/bin/env node
/**
 * generate-managed-hooks.cjs
 * Reads .claude/settings.json, extracts hook basenames from all hooks[*].command entries,
 * writes .claude/hooks/managed-hooks.json (sorted, unique).
 *
 * Usage:
 *   node .claude/scripts/generate-managed-hooks.cjs          # generate
 *   node .claude/scripts/generate-managed-hooks.cjs --check  # exit 1 if manifest stale
 */

'use strict';

const fs = require('fs');
const path = require('path');

// ---------------------------------------------------------------------------
// Paths — resolved from project root (process.cwd()), not __dirname
// ---------------------------------------------------------------------------
const PROJECT_ROOT = process.cwd();
const SETTINGS_PATH = path.resolve(PROJECT_ROOT, '.claude', 'settings.json');
const MANIFEST_PATH = path.resolve(PROJECT_ROOT, '.claude', 'hooks', 'managed-hooks.json');

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

/**
 * Read and parse a JSON file.
 * [F15] try/catch + one retry after ~50ms (race condition on Windows when another
 * hook is writing settings.json simultaneously).
 */
function readJsonSync(filePath) {
  if (!fs.existsSync(filePath)) {
    throw new Error(`File not found: ${filePath}`);
  }
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch (e) {
    // Retry once after 50ms (synchronous spin — acceptable for a CLI script)
    const start = Date.now();
    while (Date.now() - start < 50) { /* spin */ }
    try {
      return JSON.parse(fs.readFileSync(filePath, 'utf8'));
    } catch (e2) {
      throw new Error(`Failed to parse JSON at ${filePath}: ${e2.message}`);
    }
  }
}

/**
 * Walk a value recursively and collect every string that looks like a hook command.
 * Returns the raw command strings.
 */
function collectCommands(value, results) {
  if (!value || typeof value !== 'object') return;
  if (Array.isArray(value)) {
    for (const item of value) collectCommands(item, results);
    return;
  }
  if (typeof value.command === 'string') {
    results.push(value.command);
  }
  for (const key of Object.keys(value)) {
    if (key !== 'command') collectCommands(value[key], results);
  }
}

/**
 * [F5] Extract hook basename from a command string.
 *
 * Matches paths that go through `.claude/hooks/` (any depth), e.g.:
 *   node ".claude/hooks/session-init.cjs"
 *   node ".claude/hooks/notifications/notify.cjs"
 *   node .claude/hooks/simplify-gate.cjs
 *
 * statusline.cjs lives at `.claude/statusline.cjs` (outside /hooks/) — excluded by design.
 *
 * Strategy:
 *   1. Regex captures everything after "hooks/" up to the file extension.
 *   2. path.basename strips any subdirectory prefix, leaving just the filename stem.
 *   3. We keep the full basename WITH extension so the manifest is unambiguous.
 */
const HOOK_RE = /hooks\/(.+?\.(cjs|mjs|js))/;

function extractHookName(command) {
  const m = HOOK_RE.exec(command);
  if (!m) return null;
  // m[1] = "notifications/notify.cjs" or "session-init.cjs"
  return path.basename(m[1]); // "notify.cjs" / "session-init.cjs"
}

// ---------------------------------------------------------------------------
// Core
// ---------------------------------------------------------------------------

function generate() {
  const settings = readJsonSync(SETTINGS_PATH);

  const commands = [];
  collectCommands(settings.hooks, commands);

  const names = new Set();
  for (const cmd of commands) {
    const name = extractHookName(cmd);
    if (name) names.add(name);
  }

  const sorted = [...names].sort();

  return {
    _comment:
      'Auto-generated by .claude/scripts/generate-managed-hooks.cjs — do not edit manually. ' +
      'Re-run the script after adding or removing hooks in .claude/settings.json.',
    managedHooks: sorted,
  };
}

// ---------------------------------------------------------------------------
// Entrypoint
// ---------------------------------------------------------------------------

const checkMode = process.argv.includes('--check');

let generated;
try {
  generated = generate();
} catch (err) {
  console.error(`[generate-managed-hooks] ERROR: ${err.message}`);
  process.exit(2);
}

if (checkMode) {
  // Compare current manifest to what we would generate
  let current;
  try {
    current = readJsonSync(MANIFEST_PATH);
  } catch (_) {
    console.error('[generate-managed-hooks] --check FAIL: manifest missing or unreadable.');
    process.exit(1);
  }

  const currentHooks = JSON.stringify(current.managedHooks ?? []);
  const generatedHooks = JSON.stringify(generated.managedHooks);

  if (currentHooks !== generatedHooks) {
    console.error(
      '[generate-managed-hooks] --check FAIL: manifest is stale.\n' +
        `  Current  (${(current.managedHooks ?? []).length} hooks): ${currentHooks}\n` +
        `  Expected (${generated.managedHooks.length} hooks): ${generatedHooks}`,
    );
    process.exit(1);
  }

  console.log(
    `[generate-managed-hooks] --check OK: manifest is up-to-date (${generated.managedHooks.length} hooks).`,
  );
  process.exit(0);
} else {
  // Write manifest
  const json = JSON.stringify(generated, null, 2) + '\n';
  fs.writeFileSync(MANIFEST_PATH, json, 'utf8');
  console.log(
    `[generate-managed-hooks] Written ${MANIFEST_PATH} (${generated.managedHooks.length} hooks): ` +
      generated.managedHooks.join(', '),
  );
}
